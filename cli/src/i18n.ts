export type CliMessageKey = keyof typeof messages['en-US']

export function t(locale: CliLocale, key: CliMessageKey, values: Record<string, string | number> = {}): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`))
}
